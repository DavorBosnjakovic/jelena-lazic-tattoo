// jela-website/scripts/gen-hero-images.mjs
//
// Builds src/lib/heroImages.ts from the hero photos, reading each file's real
// dimensions so next/image can reserve the right height and the looping track
// never shifts while images load.
//
// Source folder, in order of preference:
//   public/hero/      files named 1.jpg, 2.jpg, ... (the purpose-cut close-ups)
//   public/portfolio/ portfolio-*.webp (fallback / placeholder)
//
// Run: node scripts/gen-hero-images.mjs

import fs from 'fs'
import path from 'path'

// 8 columns are laid out, but the block is oversized and tilted, so only
// about 6 of them fall inside the viewport on a wide screen.
const COLUMNS = 8
const PER_COLUMN = 5

function imageSize(file) {
  const buf = fs.readFileSync(file)
  if (buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WEBP') {
    const fourcc = buf.toString('ascii', 12, 16)
    if (fourcc === 'VP8X') return [1 + (buf[24] | (buf[25] << 8) | (buf[26] << 16)), 1 + (buf[27] | (buf[28] << 8) | (buf[29] << 16))]
    if (fourcc === 'VP8 ') return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff]
    if (fourcc === 'VP8L') { const b = buf.readUInt32LE(21); return [1 + (b & 0x3fff), 1 + ((b >> 14) & 0x3fff)] }
  }
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let o = 2
    while (o < buf.length) {
      if (buf[o] !== 0xff) { o++; continue }
      const marker = buf[o + 1]
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
        return [buf.readUInt16BE(o + 7), buf.readUInt16BE(o + 5)]
      }
      o += 2 + buf.readUInt16BE(o + 2)
    }
  }
  if (buf.toString('ascii', 1, 4) === 'PNG') return [buf.readUInt32BE(16), buf.readUInt32BE(20)]
  throw new Error(`ne mogu procitati dimenzije: ${file}`)
}

function collect() {
  const heroDir = path.join('public', 'hero')
  if (fs.existsSync(heroDir)) {
    const numbered = fs.readdirSync(heroDir)
      .filter((f) => /^\d+\.(jpe?g|png|webp)$/i.test(f))
      .sort((a, b) => parseInt(a, 10) - parseInt(b, 10))
    if (numbered.length) {
      return { dir: heroDir, prefix: '/hero', files: numbered }
    }
  }
  const portfolioDir = path.join('public', 'portfolio')
  return {
    dir: portfolioDir,
    prefix: '/portfolio',
    files: fs.readdirSync(portfolioDir).filter((f) => /^portfolio-.*\.(jpe?g|png|webp)$/i.test(f)).sort(),
  }
}

const { dir, prefix, files } = collect()
const images = files.map((f) => {
  const [width, height] = imageSize(path.join(dir, f))
  return { src: `${prefix}/${f}`, width, height, ratio: width / height }
})

if (!images.length) throw new Error('nema slika')

// The photos are heavily skewed towards very tall sleeve shots, so dealing
// them in file order would give every column the same slab-like rhythm.
// Split by shape and merge the two pools evenly, so long and short keep
// trading places down the sequence.
const LONG_BELOW = 0.5
const long = images.filter((i) => i.ratio < LONG_BELOW)
const short = images.filter((i) => i.ratio >= LONG_BELOW)

const sequence = []
let usedLong = 0
let usedShort = 0
for (let i = 0; i < COLUMNS * PER_COLUMN; i++) {
  // Whichever pool has fallen furthest behind its share goes next.
  const takeLong = short.length === 0 || (long.length > 0 && usedLong / long.length <= usedShort / short.length)
  if (takeLong) {
    sequence.push(long[usedLong % long.length])
    usedLong++
  } else {
    sequence.push(short[usedShort % short.length])
    usedShort++
  }
}

// Dealt one at a time across the columns, so neighbours never receive two
// images of the same shape in the same position.
const columns = Array.from({ length: COLUMNS }, () => [])
sequence.forEach((image, i) => columns[i % COLUMNS].push(image))

const body = columns
  .map((column) => '  [\n' + column.map((i) => `    { src: '${i.src}', width: ${i.width}, height: ${i.height} },`).join('\n') + '\n  ],')
  .join('\n')

fs.writeFileSync(
  path.join('src', 'lib', 'heroImages.ts'),
  `// jela-website/src/lib/heroImages.ts
//
// GENERATED by scripts/gen-hero-images.mjs - do not edit by hand.
// Source: ${prefix}/ (${images.length} images available)

export type HeroImage = { src: string; width: number; height: number }

export const heroColumns: HeroImage[][] = [
${body}
]
`
)

console.log(`izvor: ${prefix}/  (${images.length} slika dostupno)`)
console.log(`upisano: ${COLUMNS} stupaca x ${PER_COLUMN} slika`)
columns.forEach((c, i) => console.log(`  stupac ${i + 1}: ${c.map((x) => (x.width / x.height).toFixed(2)).join(' ')}`))
